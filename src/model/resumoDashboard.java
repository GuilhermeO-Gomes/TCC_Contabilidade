package model;

public class resumoDashboard {

    private String lancamentosNoMes;
    private String receitas;
    private String despesas;
    private String resultado;

    public String getLancamentosNoMes() {
        return lancamentosNoMes;
    }

    public void setLancamentosNoMes(String lancamentosNoMes) {
        this.lancamentosNoMes = lancamentosNoMes;
    }

    public String getReceitas() {
        return receitas;
    }

    public void setReceitas(String receitas) {
        this.receitas = receitas;
    }

    public String getDespesas() {
        return despesas;
    }

    public void setDespesas(String despesas) {
        this.despesas = despesas;
    }

    public String getResultado() {
        return resultado;
    }

    public void setResultado(String resultado) {
        this.resultado = resultado;
    }
}
